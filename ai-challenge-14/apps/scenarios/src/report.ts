import type { AuditEntry, Claim } from '@claims/engine';
import type { CheckRecord, StepRecord } from './context';

export interface ScenarioResult {
  id: string;
  title: string;
  summary: string;
  claimId: string | null;
  steps: StepRecord[];
  checks: CheckRecord[];
  logs: string[];
  /** Set when the scenario threw before finishing. */
  error?: string;
  passed: boolean;
}

export interface ReadBack {
  claim: Claim | null;
  audit: AuditEntry[];
}

export interface RunInfo {
  database: string;
  config: string;
  clockStart: string;
  clockEnd: string;
}

export const mark = (passed: boolean) => (passed ? '✅' : '❌');

/** Keeps a value on one table row. */
const cell = (value: unknown) =>
  String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, ' ');

const code = (value: string) => (value === '' || value === '—' ? value : `\`${value.replace(/`/g, "'")}\``);

function auditDetail(entry: AuditEntry): string {
  const data = entry.data ?? {};
  switch (entry.type) {
    case 'SIDE_EFFECT': {
      const result = data.result as Record<string, unknown> | undefined;
      const outcome = data.status === 'ok' ? 'ok' : `failed: ${String(data.error)}`;
      const shown = result?.message ?? (result === undefined ? undefined : JSON.stringify(result));
      return `${String(data.name)} (${outcome})${shown === undefined ? '' : ` — ${String(shown)}`}`;
    }
    case 'TRANSITION_REJECTED':
    case 'ACTION_REJECTED':
      return String(data.code);
    default:
      return Object.keys(data).length > 0 ? JSON.stringify(data) : '';
  }
}

export function stepsTable(steps: StepRecord[]): string[] {
  return [
    '| # | fake clock | user (role) | request | expected | actual | |',
    '|---|---|---|---|---|---|---|',
    ...steps.map(
      (s) =>
        `| ${s.n} | ${s.at} | ${s.actor} | ${code(cell(s.action))} | ${cell(s.expected)} | ${cell(s.actual)} | ${mark(s.passed)} |`,
    ),
  ];
}

export const checkList = (checks: CheckRecord[]): string[] =>
  checks.map((c) => `- ${mark(c.passed)} ${c.label}${c.detail ? ` — ${c.detail}` : ''}`);

export const logBlock = (logs: string[]): string[] => (logs.length === 0 ? ['_None._'] : ['```text', ...logs, '```']);

export function auditTable(audit: AuditEntry[]): string[] {
  const lines = [
    '| seq | timestamp | type | from → to | transition | triggered by | reason | details |',
    '|---|---|---|---|---|---|---|---|',
  ];
  for (const e of audit) {
    lines.push(
      `| ${e.seq} | ${e.timestamp} | ${e.type} | ${e.fromState ?? '∅'} → ${e.toState ?? '∅'} | ${e.transitionId ?? ''} | ` +
        `${e.triggeredBy.userId} (${e.triggeredBy.role}) | ${cell(e.reason)} | ${cell(auditDetail(e))} |`,
    );
  }
  return lines;
}

export function renderMarkdown(info: RunInfo, results: ScenarioResult[], readBack: Map<string, ReadBack>): string {
  const allPassed = results.every((r) => r.passed);
  const out: string[] = [
    '# Scenario results',
    '',
    'Generated by `pnpm scenarios` (`apps/scenarios`). Do not edit by hand; re-run the command instead.',
    '',
    '> Audit entry UUIDs and the winner of scenario 8 change on every run; this is intentional. ' +
      'Scenario 8 is a real race on the row lock, so either request may win.',
    '',
    `- Database: \`${info.database}\` (schema dropped and migrated at the start of every run)`,
    `- Config: ${info.config.split(' + ').map((file) => `\`${file}\``).join(' + ')}`,
    `- Store: \`PostgresWorkflowStore\`; engine: \`WorkflowEngine\` with the built-in rules and side effects`,
    `- Clock: \`FakeClock\` from ${info.clockStart} to ${info.clockEnd}, 1 minute between requests; ` +
      'appeal deadlines are reached by advancing the clock, never by editing `stateEnteredAt`',
    '- Audit trails below and in [`audit-output.json`](audit-output.json) are read back from the `audit_entries` table after all scenarios ran',
    '',
    `**Result: ${results.filter((r) => r.passed).length}/${results.length} scenarios passed ${mark(allPassed)}**`,
    '',
    '| # | Scenario | Claim | Final state | Audit entries | Steps | Checks | Result |',
    '|---|---|---|---|---|---|---|---|',
  ];

  for (const r of results) {
    const rb = r.claimId ? readBack.get(r.claimId) : undefined;
    const stepsPassed = r.steps.filter((s) => s.passed).length;
    const checksPassed = r.checks.filter((c) => c.passed).length;
    out.push(
      `| ${r.id} | [${r.title}](#scenario-${r.id}) | ${r.claimId ?? '—'} | ${rb?.claim?.status ?? '—'} | ` +
        `${rb?.audit.length ?? 0} | ${stepsPassed}/${r.steps.length} | ${checksPassed}/${r.checks.length} | ${mark(r.passed)} |`,
    );
  }

  for (const r of results) {
    const rb = r.claimId ? readBack.get(r.claimId) : undefined;
    out.push('', `<a id="scenario-${r.id}"></a>`, '', `## ${r.id}. ${r.title} ${mark(r.passed)}`, '', r.summary, '');
    if (r.claimId) out.push(`Claim: \`${r.claimId}\``, '');
    if (r.error) out.push(`**Scenario aborted:** ${r.error}`, '');

    out.push('### Steps', '', ...stepsTable(r.steps));
    out.push('', '### Checks on data read back from PostgreSQL', '', ...checkList(r.checks));
    out.push('', '### Side effect console output', '', ...logBlock(r.logs));

    if (rb) {
      out.push('', '### Audit trail', '', ...auditTable(rb.audit));
      if (rb.claim) out.push('', '<details><summary>Final claim</summary>', '', '```json', JSON.stringify(rb.claim, null, 2), '```', '', '</details>');
    }
  }

  return `${out.join('\n')}\n`;
}

export function renderAuditJson(info: RunInfo, results: ScenarioResult[], readBack: Map<string, ReadBack>): string {
  return `${JSON.stringify(
    {
      generatedBy: 'pnpm scenarios',
      source: `audit_entries in ${info.database}, read back with PostgresWorkflowStore.listAuditByClaim after all scenarios ran`,
      config: info.config,
      clock: { start: info.clockStart, end: info.clockEnd },
      claims: results
        .filter((r) => r.claimId !== null)
        .map((r) => {
          const rb = readBack.get(r.claimId!);
          return {
            scenario: `${r.id}. ${r.title}`,
            claimId: r.claimId,
            finalStatus: rb?.claim?.status ?? null,
            entries: rb?.audit.length ?? 0,
            audit: rb?.audit ?? [],
          };
        }),
    },
    null,
    2,
  )}\n`;
}
